/* ========================================================================
 * CRC-16/CCITT-FALSE
 * ======================================================================== */

uint16_t fmc16_crc16(const uint16_t *data, uint16_t count)
{
    uint16_t crc = 0xFFFFu;
    for (uint16_t i = 0; i < count; i++)
    {
        uint16_t w = data[i];
        /* 高字节先处理 (bit15→bit8) */
        uint8_t hi = (uint8_t)(w >> 8);
        crc = (uint16_t)((crc << 8) ^ s_crc16_table[((crc >> 8) ^ hi) & 0xFF]);
        /* 低字节后处理 (bit7→bit0) */
        uint8_t lo = (uint8_t)(w & 0xFF);
        crc = (uint16_t)((crc << 8) ^ s_crc16_table[((crc >> 8) ^ lo) & 0xFF]);
    }
    return crc;
}

/* ========================================================================
 * CRC-32/MPEG-2
 * ======================================================================== */

uint32_t fmc16_crc32(const uint16_t *data, uint16_t count)
{
    uint32_t crc = 0xFFFFFFFFu;
    for (uint16_t i = 0; i < count; i++)
    {
        uint16_t w = data[i];
        /* 高字节先 (bit15→bit8) */
        uint8_t hi = (uint8_t)(w >> 8);
        crc = (crc << 8) ^ s_crc32_table[((crc >> 24) ^ hi) & 0xFF];
        /* 低字节后 (bit7→bit0) */
        uint8_t lo = (uint8_t)(w & 0xFF);
        crc = (crc << 8) ^ s_crc32_table[((crc >> 24) ^ lo) & 0xFF];
    }
    return crc;
}

/* ========================================================================
 * Golden Vector 自检
 * ======================================================================== */

int fmc16_crc_selftest(void)
{
    /* 协议 §5: ACK golden vector (19 words)
     * XO2→STM32, seq=1, trans=1, 确认 COMMAND/GET_CAPABILITIES
     */
    static const uint16_t golden[] = {
        0xA55A,  /* W0:  SOF0 */
        0x5AA5,  /* W1:  SOF1 */
        0x100D,  /* W2:  VERSION_HEADER */
        0x0013,  /* W3:  TOTAL_WORDS = 19 */
        0x0300,  /* W4:  TYPE=ACK(0x03), FLAGS=0 */
        0x0100,  /* W5:  SRC=0x01(XO2), DST=0x00(STM32) */
        0x0000,  /* W6:  CHANNEL=0 (link mgmt) */
        0x0004,  /* W7:  PAYLOAD_WORDS=4 */
        0x0000,  /* W8:  SEQ_H */
        0x0001,  /* W9:  SEQ_L */
        0x0000,  /* W10: TRANS_H */
        0x0001,  /* W11: TRANS_L */
        0x0141,  /* W12: HEADER_CRC16 (W2~W11) */
        0x0030,  /* W13: P0 (ACK payload: original msg type) */
        0x0001,  /* W14: P1 (original opcode) */
        0x0001,  /* W15: P2 (ACCEPTED) */
        0x0000,  /* W16: P3 (detail) */
        0xF1E8,  /* W17: CRC32_HI */
        0x829E,  /* W18: CRC32_LO */
    };

    /* 验证 Header CRC (W2~W11 = 10 words) */
    uint16_t computed_hdr_crc = fmc16_crc16(&golden[2], 10);
    if (computed_hdr_crc != 0x0141u)
    {
        printf("[FMC16] CRC selftest FAIL: Header CRC16=0x%04X, expected 0x0141\r\n",
               computed_hdr_crc);
        return 0;
    }

    /* 验证 Packet CRC (W2~W17 = 16 words, 含 W12 的 Header CRC) */
    uint32_t computed_pkt_crc = fmc16_crc32(&golden[2], 16);
    uint32_t expected_pkt_crc = FMC16_U32(golden[17], golden[18]);  /* 0xF1E8829E */

    if (computed_pkt_crc != expected_pkt_crc)
    {
        printf("[FMC16] CRC selftest FAIL: Packet CRC32=0x%08lX, expected 0x%08lX\r\n",
               (unsigned long)computed_pkt_crc,
               (unsigned long)expected_pkt_crc);
        return 0;
    }

    printf("[FMC16] CRC selftest PASS (Header=0x0141, Packet=0xF1E8829E)\r\n");
    return 1;
}
