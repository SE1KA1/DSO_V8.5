uint8_t dallas_crc8(uint8_t *data, uint8_t size)
{
    unsigned char crc = 0, inbyte, j, mix;
	unsigned int i;
	
    for (i = 0; i < size; ++i )
    {
        inbyte = data[i];
        for (j = 0; j < 8; ++j )
        {
            mix = (crc ^ inbyte) & 0x01;
            crc >>= 1;
            if ( mix ) crc ^= 0x8C;
            inbyte >>= 1;
        }
    }
	
    return crc;
}

