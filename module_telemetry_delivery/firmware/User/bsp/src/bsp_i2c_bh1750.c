void BH1750_AdjustSensitivity(uint8_t _ucMTReg)
{
	if (_ucMTReg <= 31)
	{
		_ucMTReg = 31;
	}
	else if (_ucMTReg >= 254)
	{
		_ucMTReg = 254;
	}
	
	s_MTReg = _ucMTReg;
	
	BH1750_WriteCmd(0x40 + (s_MTReg >> 5));		/* ���ĸ�3bit */
	BH1750_WriteCmd(0x60 + (s_MTReg & 0x1F));	/* ���ĵ�5bit */
	
	/*���������̷�Χ����Ҫ���·����������ò���ģʽ��*/
	BH1750_ChageMode(s_Mode);
}

